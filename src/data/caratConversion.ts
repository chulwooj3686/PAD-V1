/**
 * 1.0 ~ 5.0 사이의 원점수를 받아 표에 정의된 정확한 T점수(20.0~80.0)와 백분위(1.0~99.0)를 반환합니다.
 * 소수점 사이의 값(예: 3.25)은 선형 보간(linear interpolation) 처리합니다.
 */
export function convertCaratScores(category: string, rawScore: number): { tScore: number; percentile: number } {
  const entry = caratConversionTable[category];
  if (!entry) {
    return {
      tScore: Math.round((20 + (rawScore - 1) * 15) * 10) / 10,
      percentile: Math.round(rawScore * 20 * 10) / 10
    };
  }

  const clamped = Math.max(1.0, Math.min(5.0, rawScore));
  const index = (clamped - 1.0) * 10;
  const lowerIndex = Math.floor(index);
  const upperIndex = Math.ceil(index);

  if (lowerIndex === upperIndex || lowerIndex >= 40) {
    const safeIdx = Math.min(40, lowerIndex);
    return {
      tScore: entry.tScore[safeIdx],
      percentile: entry.percentile[safeIdx]
    };
  }

  const fraction = index - lowerIndex;
  const t = entry.tScore[lowerIndex] + (entry.tScore[upperIndex] - entry.tScore[lowerIndex]) * fraction;
  const p = entry.percentile[lowerIndex] + (entry.percentile[upperIndex] - entry.percentile[lowerIndex]) * fraction;

  return {
    tScore: Math.round(t * 10) / 10,
    percentile: Math.round(p * 10) / 10
  };
}
